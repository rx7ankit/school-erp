// Generates dist/tokens.css and dist/tailwind.css from tokens.json (single source of truth).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("./tokens.json", import.meta.url)));
const out = (name, s) => {
  mkdirSync(new URL("./dist/", import.meta.url), { recursive: true });
  writeFileSync(new URL(`./dist/${name}`, import.meta.url), s);
};
const vars = (obj, prefix, indent = "  ") =>
  Object.entries(obj).map(([k, v]) => `${indent}--${prefix}-${k}: ${v};`).join("\n");

const light = vars(t.color.light, "c");
const type = Object.entries(t.text).map(([k, v]) =>
  [`size`, `line`, `weight`, `tracking`].map((p) => `  --text-${k}-${p}: ${v[p]};`).join("\n")).join("\n");

const css = `/* GENERATED by build.mjs — edit tokens.json, not this file. */
:root {
  color-scheme: light;
${light}
${vars(t.radius, "radius")}
${vars(t.space, "space")}
${vars(t.control, "control")}
${vars(t.motion, "motion")}
  --fw-heading: ${t.weight.heading};
  --fw-ui: ${t.weight.ui};
  --font-sans: ${t.font.sans};
  --font-mono: ${t.font.mono};
${type}
  --shadow: none; /* no shadows anywhere */
}

/* Elevation is expressed with fills, never shadows */
*, *::before, *::after { box-shadow: none !important; text-shadow: none !important; }

h1, h2, h3 { font-weight: var(--fw-heading); text-wrap: balance; }
/* Two-tone heading: <h1>Ink phrase. <span class="dim">Grey phrase.</span></h1> */
.dim { color: var(--c-text-tertiary); }

body {
  background: var(--c-bg);
  color: var(--c-text);
  font-family: var(--font-sans);
  font-size: var(--text-body-size);
  line-height: var(--text-body-line);
  letter-spacing: var(--text-body-tracking);
  -webkit-font-smoothing: antialiased;
}
`;
out("tokens.css", css);

